    print(f"\nFinal State Vector Shape: {state_vector_df.shape}")
    print(f"Feature Columns ({len(state_vector_df.columns)}): {list(state_vector_df.columns)}\n")
    print("First 5 rows of the final State Vector DataFrame:")
