"""
MarketDataProcessor Module
===========================
A production-grade Python module designed for Reinforcement Learning (RL) trading systems.
Handles data ingestion via Yahoo Finance, technical indicator engineering via the `ta` library,
data cleaning, and feature normalization with scikit-learn's MinMaxScaler.
"""

from typing import List, Optional, Union
import numpy as np
import pandas as pd
from sklearn.preprocessing import MinMaxScaler
import yfinance as yf

# Technical Analysis library imports
from ta.momentum import RSIIndicator
from ta.trend import ADXIndicator, MACD
from ta.volatility import AverageTrueRange, BollingerBands


class MarketDataProcessor:
    """
    Ingests and transforms financial market data into structured state vectors
    tailored for Reinforcement Learning (RL) neural network architectures.

    Key Capabilities:
    -----------------
    1. Data Ingestion: Downloads historical OHLCV data via yfinance, resolving
       multi-level column indices and enforcing standard numeric typing.
    2. Indicator Engineering: Computes momentum (RSI, MACD), volatility (ATR,
       Bollinger Bands), and trend (ADX) using the `ta` library.
    3. Data Cleaning: Forward-fills sporadic market gaps and eliminates initial
       burn-in NaN rows generated by rolling window computations.
    4. Feature Normalization: Scales price and volume features to [0, 1] using
       scikit-learn's MinMaxScaler while preserving bounded (RSI, ADX) and
       zero-centered differential signals (MACD).
    5. State Vector Output: Returns a clean, high-density DataFrame ready for
       direct feeding into RL environments (e.g., Gym, Gymnasium, FinRL).
    """

    def __init__(
        self,
        scaler: Optional[MinMaxScaler] = None,
        scale_columns: Optional[List[str]] = None,
    ) -> None:
        """
        Initializes the MarketDataProcessor.

        Args:
            scaler: An optional pre-configured MinMaxScaler instance. If None,
                    a standard MinMaxScaler(feature_range=(0, 1)) is instantiated.
            scale_columns: Explicit list of column names to normalize. Defaults
                           to standard price & volume columns:
                           ['Open', 'High', 'Low', 'Close', 'Volume'].
        """
        self.scaler: MinMaxScaler = scaler if scaler is not None else MinMaxScaler(feature_range=(0, 1))
        self.scale_columns: List[str] = (
            scale_columns
            if scale_columns is not None
            else ["Open", "High", "Low", "Close", "Volume"]
        )
        self._is_fitted: bool = False

    def fetch_data(
        self,
        ticker: str,
        start: Optional[Union[str, pd.Timestamp]] = None,
        end: Optional[Union[str, pd.Timestamp]] = None,
        period: str = "2y",
        interval: str = "1d",
    ) -> pd.DataFrame:
        """
        Downloads historical OHLCV market data for a given ticker and date range.

        Args:
            ticker: The asset/stock symbol (e.g., 'AAPL', 'MSFT', 'SPY').
            start: Start date string ('YYYY-MM-DD') or pd.Timestamp.
            end: End date string ('YYYY-MM-DD') or pd.Timestamp.
            period: Fallback data period (e.g., '1y', '2y', '5y') if start/end
                    are not specified. Defaults to '2y'.
            interval: Bar frequency ('1d', '1h', etc.). Defaults to '1d'.

        Returns:
            pd.DataFrame: Raw OHLCV DataFrame with standardized columns
                          ['Open', 'High', 'Low', 'Close', 'Volume'].
        """
        download_kwargs = {
            "tickers": ticker,
            "interval": interval,
            "auto_adjust": False,
            "progress": False,
        }

        if start is not None:
            download_kwargs["start"] = start
            if end is not None:
                download_kwargs["end"] = end
        else:
            download_kwargs["period"] = period

        df: pd.DataFrame = yf.download(**download_kwargs)

        if df.empty:
            raise ValueError(
                f"No data returned for ticker '{ticker}' with parameters: {download_kwargs}"
            )

        # Flatten MultiIndex columns introduced in recent yfinance versions
        if isinstance(df.columns, pd.MultiIndex):
            df.columns = df.columns.get_level_values(0)

        # Normalize column names to Title Case and clean metadata
        df.columns = [str(col).strip().title() for col in df.columns]
        df.columns.name = None

        required_cols = ["Open", "High", "Low", "Close", "Volume"]
        missing_cols = [col for col in required_cols if col not in df.columns]
        if missing_cols:
            raise KeyError(
                f"Fetched data missing required OHLCV columns: {missing_cols}. "
                f"Available columns: {list(df.columns)}"
            )

        # Retain only required OHLCV columns, ensure float64 precision, and sort index
        df = df[required_cols].astype(np.float64).sort_index()
        df.index.name = "Date"
        return df

    def add_technical_indicators(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Computes momentum, volatility, and trend technical indicators using the `ta` library.

        Engineered Features:
        - Momentum:
            - RSI (14 period): Relative Strength Index.
            - MACD: MACD line (12, 26, 9), Signal line, and Difference (Histogram).
        - Volatility:
            - Average True Range (ATR, 14 period): Absolute market volatility in price units.
            - Bollinger Bands (20 period, 2 std dev): High band, Mid band (SMA), Low band.
        - Trend:
            - Average Directional Index (ADX, 14 period): Trend strength indicator.

        Args:
            df: DataFrame containing standard OHLCV columns.

        Returns:
            pd.DataFrame: DataFrame augmented with technical indicator columns.
        """
        df_feat = df.copy()

        # 1. Momentum: RSI (14 period)
        rsi_indicator = RSIIndicator(close=df_feat["Close"], window=14, fillna=False)
        df_feat["RSI"] = rsi_indicator.rsi()

        # 1. Momentum: MACD (Fast: 12, Slow: 26, Signal: 9)
        macd_indicator = MACD(
            close=df_feat["Close"],
            window_slow=26,
            window_fast=12,
            window_sign=9,
            fillna=False,
        )
        df_feat["MACD"] = macd_indicator.macd()
        df_feat["MACD_Signal"] = macd_indicator.macd_signal()
        df_feat["MACD_Diff"] = macd_indicator.macd_diff()

        # 2. Volatility: Average True Range (14 period)
        atr_indicator = AverageTrueRange(
            high=df_feat["High"],
            low=df_feat["Low"],
            close=df_feat["Close"],
            window=14,
            fillna=False,
        )
        df_feat["ATR"] = atr_indicator.average_true_range()

        # 2. Volatility: Bollinger Bands (20 period, 2 std dev)
        bb_indicator = BollingerBands(
            close=df_feat["Close"],
            window=20,
            window_dev=2,
            fillna=False,
        )
        df_feat["BB_High"] = bb_indicator.bollinger_hband()
        df_feat["BB_Mid"] = bb_indicator.bollinger_mavg()
        df_feat["BB_Low"] = bb_indicator.bollinger_lband()

        # 3. Trend: Average Directional Index (14 period)
        adx_indicator = ADXIndicator(
            high=df_feat["High"],
            low=df_feat["Low"],
            close=df_feat["Close"],
            window=14,
            fillna=False,
        )
        df_feat["ADX"] = adx_indicator.adx()

        return df_feat

    def clean_data(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Performs robust data cleaning on the engineered dataset:
        1. Forward-fills sporadic missing observations (handling exchange holidays/gaps).
        2. Drops rows with remaining NaNs caused by the rolling window burn-in period.

        Args:
            df: DataFrame containing technical indicators and potential NaNs.

        Returns:
            pd.DataFrame: Cleaned DataFrame with complete observations across all features.
        """
        cleaned_df = df.copy()
        # Forward-fill missing values
        cleaned_df = cleaned_df.ffill()
        # Drop rows with NaNs (e.g., initial 33+ rows needed to compute 26-period EMA / 14-period ADX)
        cleaned_df = cleaned_df.dropna()
        return cleaned_df

    def normalize_features(
        self,
        df: pd.DataFrame,
        columns_to_scale: Optional[List[str]] = None,
        fit_scaler: bool = True,
    ) -> pd.DataFrame:
        """
        Normalizes price and volume features to the range [0, 1] using MinMaxScaler.

        Design Rationale for RL State Representation:
        ---------------------------------------------
        - Price and Volume columns ('Open', 'High', 'Low', 'Close', 'Volume') are
          scaled to [0, 1] to prevent large raw dollar/share values from destabilizing
          gradient updates in neural networks.
        - RSI and ADX are NOT normalized because they are already bounded by definition
          within [0, 100].
        - MACD is strictly NOT normalized because its zero-line crossing is critical
          directional signal; MinMax scaling would distort negative/positive relationships.

        Args:
            df: DataFrame containing cleaned features.
            columns_to_scale: Columns to normalize. Defaults to `self.scale_columns`.
            fit_scaler: If True, fits and transforms the data (training mode).
                        If False, transforms using an existing fitted scaler (inference mode,
                        preventing lookahead bias during RL evaluation/testing).

        Returns:
            pd.DataFrame: DataFrame with normalized price and volume features.
        """
        target_cols = columns_to_scale if columns_to_scale is not None else self.scale_columns
        missing = [col for col in target_cols if col not in df.columns]
        if missing:
            raise KeyError(f"Columns specified for scaling not found in DataFrame: {missing}")

        normalized_df = df.copy()

        if fit_scaler:
            normalized_df[target_cols] = self.scaler.fit_transform(normalized_df[target_cols])
            self._is_fitted = True
        else:
            if not self._is_fitted:
                raise RuntimeError(
                    "MinMaxScaler is not fitted yet. Call normalize_features with fit_scaler=True "
                    "or process training data first before running inference."
                )
            normalized_df[target_cols] = self.scaler.transform(normalized_df[target_cols])

        return normalized_df

    def process(
        self,
        ticker: str,
        start: Optional[Union[str, pd.Timestamp]] = None,
        end: Optional[Union[str, pd.Timestamp]] = None,
        period: str = "2y",
        interval: str = "1d",
        fit_scaler: bool = True,
    ) -> pd.DataFrame:
        """
        Executes the complete end-to-end data processing pipeline:
        1. Ingestion: Fetches historical OHLCV data for the given ticker.
        2. Feature Engineering: Calculates momentum, volatility, and trend indicators.
        3. Data Cleaning: Forward-fills sporadic NaNs and drops rolling-window burn-in rows.
        4. Normalization: MinMax scales price/volume features to [0, 1].

        Args:
            ticker: Asset ticker symbol (e.g., 'AAPL').
            start: Optional start date for data download.
            end: Optional end date for data download.
            period: Fallback period (default '2y') if start/end are not provided.
            interval: Historical bar interval (default '1d').
            fit_scaler: Whether to fit the MinMaxScaler (default True).

        Returns:
            pd.DataFrame: A clean, fully engineered DataFrame where every row
                          represents a complete State Vector ready for RL neural networks.
        """
        raw_df = self.fetch_data(
            ticker=ticker,
            start=start,
            end=end,
            period=period,
            interval=interval,
        )
        return self.process_dataframe(raw_df, fit_scaler=fit_scaler)

    def process_dataframe(
        self,
        df: pd.DataFrame,
        fit_scaler: bool = True,
    ) -> pd.DataFrame:
        """
        Processes an existing OHLCV DataFrame through indicator engineering, cleaning,
        and normalization without re-downloading.

        Args:
            df: Input OHLCV DataFrame.
            fit_scaler: Whether to fit the MinMaxScaler.

        Returns:
            pd.DataFrame: Engineered state vector DataFrame.
        """
        engineered_df = self.add_technical_indicators(df)
        cleaned_df = self.clean_data(engineered_df)
        state_vector_df = self.normalize_features(cleaned_df, fit_scaler=fit_scaler)
        return state_vector_df


if __name__ == "__main__":
    # Instantiate the processor
    processor = MarketDataProcessor()

    # Process 2 years of daily data for Apple ('AAPL')
    print("Fetching and processing 2 years of daily data for 'AAPL'...")
    state_vector_df = processor.process(ticker="AAPL", period="2y", interval="1d")

